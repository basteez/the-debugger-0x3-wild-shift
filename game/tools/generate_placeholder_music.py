#!/usr/bin/env python3
"""Generates the PLACEHOLDER music loops (Story 7.1, FR62, AC 15, D-S71-9).

Output (Ogg Vorbis, mono, 22050 Hz, all exactly LOOP_SECONDS long, imported with loop on):
    game/assets/audio/music/title.ogg               title / intro / ending loop
    game/assets/audio/music/boss_1.ogg              Infinite Loop fight (boss index 0)
    game/assets/audio/music/boss_2.ogg              Null Pointer fight (boss index 1)
    game/assets/audio/music/boss_3.ogg              Segfault fight (boss index 2)
    game/assets/audio/music/boss_N_glitch.ogg       phase-3 variant of boss_N: the same pattern
                                                    +2 semitones, bit-crushed (4-bit, 1/4 rate)
    game/assets/audio/music/breakpoint_muffled.ogg  the shared pattern through a one-pole
                                                    low-pass at ~600 Hz (pre-rendered, no live effect)

Every loop has the same tempo (120 BPM) and length (4 bars of 4/4 = 8 s), so AudioManager can
start a variant at the playing track's position and stay on the bar (D-S71-8). The real
BeepBox tracks replace these files later with the same names; see
game/assets/audio/music/README.md for the replacement rule.

The sounds are generated by this project's own code, so they are CC0 by construction.

Dependencies (not in the standard library): numpy and soundfile (the soundfile wheel bundles
libsndfile with the Vorbis encoder). Install them in a throwaway virtual env, never system-wide:
    python3 -m venv /tmp/music-venv
    /tmp/music-venv/bin/pip install numpy soundfile
Run from the repo root:
    /tmp/music-venv/bin/python game/tools/generate_placeholder_music.py
then let Godot re-import (open the editor, or `godot --headless --path game --import`).

Deterministic: no RNG. libsndfile picks a random Ogg stream serial number, so the script
rewrites every page's serial to a fixed value and recomputes the page CRCs; two runs give
byte-identical files (with the same libsndfile version).
"""

import io
import os
import struct

import numpy as np
import soundfile as sf

MIX_RATE = 22050
BPM = 120.0
BARS = 4
BEATS_PER_BAR = 4
STEPS_PER_BEAT = 4 # 16th-note arpeggio
LOOP_SECONDS = BARS * BEATS_PER_BAR * 60.0 / BPM
LOOP_FRAMES = int(round(LOOP_SECONDS * MIX_RATE))
TOTAL_STEPS = BARS * BEATS_PER_BAR * STEPS_PER_BEAT
ATTACK_FRAMES = 40
RELEASE_FRAMES = 400
ARP_AMPLITUDE = 0.22
BASS_AMPLITUDE = 0.30
SQUARE_DUTY = 0.25
GLITCH_SEMITONES = 2
GLITCH_BITS = 4
GLITCH_HOLD = 4 # sample-and-hold factor (rate crush)
MUFFLE_CUTOFF_HZ = 600.0
MUFFLE_GAIN = 0.8
VORBIS_QUALITY = 0.4 # soundfile compression_level: 0 = best quality, 1 = smallest
OGG_SERIAL = 0x7100_0001
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "audio", "music")

# One chord root per bar (MIDI note), chord shape (semitones from the root), bass octave offset.
PATTERNS = {
    "title": ([57, 53, 48, 55], [0, 3, 7, 12]),    # A minor - F - C - G, calm
    "boss_1": ([50, 50, 53, 48], [0, 7, 12, 7]),   # D, looping fifths (Infinite Loop)
    "boss_2": ([52, 48, 50, 47], [0, 3, 6, 10]),   # E, diminished colour (Null Pointer)
    "boss_3": ([45, 46, 45, 44], [0, 1, 7, 13]),   # A, chromatic grind (Segfault)
    "shared": ([48, 48, 53, 55], [0, 4, 7, 12]),   # the muffled Breakpoint pattern
}


def midi_hz(note: float) -> float:
    return 440.0 * 2.0 ** ((note - 69.0) / 12.0)


def envelope(length: int) -> np.ndarray:
    env = np.ones(length)
    attack = min(ATTACK_FRAMES, length)
    env[:attack] = np.linspace(0.0, 1.0, attack, endpoint=False)
    release = min(RELEASE_FRAMES, length)
    env[length - release:] *= np.linspace(1.0, 0.0, release)
    return env


def square(hz: float, length: int) -> np.ndarray:
    phase = (np.arange(length) * hz / MIX_RATE) % 1.0
    return np.where(phase < SQUARE_DUTY, 1.0, -1.0)


def triangle(hz: float, length: int) -> np.ndarray:
    phase = (np.arange(length) * hz / MIX_RATE) % 1.0
    return 4.0 * np.abs(phase - 0.5) - 1.0


def step_frame(step: int) -> int:
    """First frame of a 16th step (rounded, so the steps tile the loop exactly)."""
    return int(round(step * LOOP_FRAMES / TOTAL_STEPS))


def render(pattern: tuple, transpose: int = 0) -> np.ndarray:
    """Square arpeggio (16ths) plus triangle bass (8ths), every note enveloped to zero."""
    roots, shape = pattern
    out = np.zeros(LOOP_FRAMES)
    steps_per_bar = BEATS_PER_BAR * STEPS_PER_BEAT
    for bar, root in enumerate(roots):
        for step in range(steps_per_bar):
            index = bar * steps_per_bar + step
            start, end = step_frame(index), step_frame(index + 1)
            note = root + transpose + 12 + shape[step % len(shape)]
            out[start:end] += ARP_AMPLITUDE * square(midi_hz(note), end - start) * envelope(end - start)
        for eighth in range(steps_per_bar // 2):
            index = bar * steps_per_bar + eighth * 2
            start, end = step_frame(index), step_frame(index + 2)
            note = root + transpose - 12 + (7 if eighth % 2 else 0)
            out[start:end] += BASS_AMPLITUDE * triangle(midi_hz(note), end - start) * envelope(end - start)
    return out


def bitcrush(signal: np.ndarray) -> np.ndarray:
    held = np.repeat(signal[::GLITCH_HOLD], GLITCH_HOLD)[:signal.size]
    levels = 2 ** (GLITCH_BITS - 1)
    return np.round(held * levels) / levels


def low_pass(signal: np.ndarray) -> np.ndarray:
    """One-pole low-pass, run over the loop twice so the filter state wraps (seamless loop)."""
    alpha = 1.0 - np.exp(-2.0 * np.pi * MUFFLE_CUTOFF_HZ / MIX_RATE)
    out = np.zeros(signal.size)
    state = 0.0
    for _ in range(2):
        for i in range(signal.size):
            state += alpha * (signal[i] - state)
            out[i] = state
    return out * MUFFLE_GAIN


def _crc_table() -> list:
    table = []
    for i in range(256):
        r = i << 24
        for _ in range(8):
            r = ((r << 1) ^ 0x04C11DB7) if r & 0x80000000 else (r << 1)
        table.append(r & 0xFFFFFFFF)
    return table


CRC_TABLE = _crc_table()


def ogg_crc(data: bytes) -> int:
    crc = 0
    for byte in data:
        crc = ((crc << 8) & 0xFFFFFFFF) ^ CRC_TABLE[((crc >> 24) & 0xFF) ^ byte]
    return crc


def fix_serial(ogg: bytes) -> bytes:
    """Rewrites every Ogg page's stream serial to OGG_SERIAL and recomputes the page CRC."""
    out = bytearray()
    pos = 0
    while pos < len(ogg):
        if ogg[pos:pos + 4] != b"OggS":
            raise ValueError("not an Ogg page at byte %d" % pos)
        segments = ogg[pos + 26]
        body = sum(ogg[pos + 27:pos + 27 + segments])
        page = bytearray(ogg[pos:pos + 27 + segments + body])
        struct.pack_into("<I", page, 14, OGG_SERIAL)
        struct.pack_into("<I", page, 22, 0)
        struct.pack_into("<I", page, 22, ogg_crc(bytes(page)))
        out += page
        pos += len(page)
    return bytes(out)


def write_ogg(name: str, signal: np.ndarray) -> None:
    assert signal.size == LOOP_FRAMES
    buffer = io.BytesIO()
    sf.write(buffer, np.clip(signal, -1.0, 1.0).astype(np.float32), MIX_RATE, format="OGG",
            subtype="VORBIS", compression_level=VORBIS_QUALITY)
    path = os.path.join(OUT_DIR, name)
    with open(path, "wb") as handle:
        handle.write(fix_serial(buffer.getvalue()))
    print("wrote %s (%d frames, %.2f s)" % (os.path.normpath(path), signal.size, signal.size / MIX_RATE))


def main() -> None:
    write_ogg("title.ogg", render(PATTERNS["title"]))
    for index in (1, 2, 3):
        pattern = PATTERNS["boss_%d" % index]
        write_ogg("boss_%d.ogg" % index, render(pattern))
        write_ogg("boss_%d_glitch.ogg" % index, bitcrush(render(pattern, GLITCH_SEMITONES)))
    write_ogg("breakpoint_muffled.ogg", low_pass(render(PATTERNS["shared"])))


if __name__ == "__main__":
    main()
