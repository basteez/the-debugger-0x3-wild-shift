#!/usr/bin/env python3
"""Generates the placeholder shift key-click SFX (Story 2.4, FR28, FR63, D-S24-5).

Output (16-bit mono PCM WAV, 22050 Hz, 40 ms, imported by Godot as AudioStreamWAV):
    game/assets/audio/sfx/shift_left.wav   down-sweep 1200 Hz -> 800 Hz (`<<`)
    game/assets/audio/sfx/shift_right.wav  up-sweep    800 Hz -> 1200 Hz (`>>`)

The sounds are generated by this project's own code, so they are CC0 by construction.
They are placeholders: the final SFX pass is Story 7.2.

Run from the repo root (standard library only, no packages):
    python3 game/tools/gen_shift_sfx.py
The output is deterministic: running it twice gives byte-identical files.
"""

import math
import os
import struct
import wave

MIX_RATE = 22050
SECONDS = 0.040
AMPLITUDE = 0.5
## Fraction of the clip (at the end) faded linearly to silence, so the clip ends without a click.
FADE_FRACTION = 0.25
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "audio", "sfx")
CLIPS = {
    "shift_left.wav": (1200.0, 800.0),
    "shift_right.wav": (800.0, 1200.0),
}


def sweep(f0: float, f1: float) -> bytes:
    """Linear frequency sweep f0 -> f1 with a fast attack and a linear fade-out."""
    frames = int(SECONDS * MIX_RATE)
    fade_start = int(frames * (1.0 - FADE_FRACTION))
    out = bytearray()
    phase = 0.0
    for i in range(frames):
        t = i / frames
        freq = f0 + (f1 - f0) * t
        phase += 2.0 * math.pi * freq / MIX_RATE
        env = 1.0
        if i >= fade_start:
            env = 1.0 - (i - fade_start) / max(frames - 1 - fade_start, 1)
        sample = int(round(math.sin(phase) * AMPLITUDE * env * 32767.0))
        out += struct.pack("<h", max(-32768, min(32767, sample)))
    return bytes(out)


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, (f0, f1) in CLIPS.items():
        path = os.path.normpath(os.path.join(OUT_DIR, name))
        with wave.open(path, "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(MIX_RATE)
            w.writeframes(sweep(f0, f1))
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
