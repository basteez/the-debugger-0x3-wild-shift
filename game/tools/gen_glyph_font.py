def glyph_rows(ch: str) -> list[str]:
    if ch in WIDE:
        rows = WIDE[ch].split("|")
        if len(rows) != CELL or any(len(r) != CELL for r in rows):
            sys.exit("bad wide glyph U+%04X" % ord(ch))
        return rows
    rows = NARROW[ch].split("|") if NARROW[ch] else []
    if len(rows) > CELL or any(len(r) != 5 for r in rows):
        sys.exit("bad narrow glyph %r" % ch)
    rows += ["....."] * (CELL - len(rows))
    return ["." + r + ".." for r in rows]


def png_bytes(width: int, height: int, rgba: bytearray) -> bytes:
    def chunk(tag: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    raw = bytearray()
    stride = width * 4
    for y in range(height):
        raw.append(0)  # filter: none
        raw += rgba[y * stride:(y + 1) * stride]
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)  # 8-bit RGBA
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b"")


def main() -> None:
    if set(NARROW) & set(WIDE):
        sys.exit("glyphs in both NARROW and WIDE: %r" % sorted(set(NARROW) & set(WIDE)))
    chars = sorted(set(NARROW) | set(WIDE), key=ord)
    for c in range(32, 127):
        if chr(c) not in NARROW:
            sys.exit("printable ASCII %r missing" % chr(c))
    rows_n = (len(chars) + ATLAS_COLS - 1) // ATLAS_COLS
    width, height = ATLAS_COLS * CELL, rows_n * CELL
    rgba = bytearray(width * height * 4)
    lines = [
        'info face="%s" size=%d bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0 outline=0' % (FACE, CELL),
        "common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4" % (CELL, CELL - 1, width, height),
        'page id=0 file="%s"' % PNG_NAME,
        "chars count=%d" % len(chars),
    ]
    for i, ch in enumerate(chars):
        gx, gy = (i % ATLAS_COLS) * CELL, (i // ATLAS_COLS) * CELL
        for y, row in enumerate(glyph_rows(ch)):
            for x, px in enumerate(row):
                if px == "#":
                    o = ((gy + y) * width + gx + x) * 4
                    rgba[o:o + 4] = b"\xff\xff\xff\xff"
        lines.append("char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15" % (ord(ch), gx, gy, CELL, CELL, CELL))
    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, PNG_NAME), "wb") as f:
        f.write(png_bytes(width, height, rgba))
    with open(os.path.join(OUT_DIR, FNT_NAME), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("gen_glyph_font: %d glyphs, atlas %dx%d" % (len(chars), width, height))


if __name__ == "__main__":
    main()
